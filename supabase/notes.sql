-- Run after setup.sql. Visitor sign-in is not needed. Apply adda.sql after this migration.
begin;
create table if not exists public.bhaai_posts(id uuid primary key default gen_random_uuid(),body text not null check(char_length(trim(body)) between 1 and 2000),created_at timestamptz not null default now());
create table if not exists public.bhaai_likes(post_id uuid references public.bhaai_posts on delete cascade,user_id uuid references auth.users on delete cascade,primary key(post_id,user_id));
create table if not exists public.bhaai_comments(id uuid primary key default gen_random_uuid(),post_id uuid not null references public.bhaai_posts on delete cascade,user_id uuid not null references auth.users on delete cascade,display_name text not null check(char_length(trim(display_name)) between 1 and 60),body text not null check(char_length(trim(body)) between 1 and 500),created_at timestamptz not null default now());
alter table public.bhaai_posts enable row level security;
alter table public.bhaai_likes enable row level security;
alter table public.bhaai_comments enable row level security;
grant select on public.bhaai_posts,public.bhaai_likes,public.bhaai_comments to anon,authenticated;
grant insert,delete on public.bhaai_posts,public.bhaai_likes,public.bhaai_comments to authenticated;
drop policy if exists "Public notes" on public.bhaai_posts;
create policy "Public notes" on public.bhaai_posts for select using(true);
drop policy if exists "Admin publishes" on public.bhaai_posts;
create policy "Admin publishes" on public.bhaai_posts for insert to authenticated with check(public.is_library_admin());
drop policy if exists "Admin removes notes" on public.bhaai_posts;
create policy "Admin removes notes" on public.bhaai_posts for delete to authenticated using(public.is_library_admin());
drop policy if exists "Public likes" on public.bhaai_likes;
create policy "Public likes" on public.bhaai_likes for select using(true);
drop policy if exists "Own like" on public.bhaai_likes;
create policy "Own like" on public.bhaai_likes for insert to authenticated with check(user_id=(select auth.uid()));
drop policy if exists "Own unlike" on public.bhaai_likes;
create policy "Own unlike" on public.bhaai_likes for delete to authenticated using(user_id=(select auth.uid()));
drop policy if exists "Public comments" on public.bhaai_comments;
create policy "Public comments" on public.bhaai_comments for select using(true);
drop policy if exists "Visitor comments" on public.bhaai_comments;
create policy "Visitor comments" on public.bhaai_comments for insert to authenticated with check(user_id=(select auth.uid()) and not exists(select 1 from public.bhaai_comments c where c.user_id=(select auth.uid()) and c.created_at>now()-interval '15 seconds'));
drop policy if exists "Admin moderates" on public.bhaai_comments;
create policy "Admin moderates" on public.bhaai_comments for delete to authenticated using(public.is_library_admin());
create index if not exists bhaai_comments_post on public.bhaai_comments(post_id,created_at);
commit;
